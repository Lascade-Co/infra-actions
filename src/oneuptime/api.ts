// ---------- endpoints and headers ----------

export const API_PREFIX = "/api";
export const PATHS = {
  monitorList: "/monitor/get-list",
  monitorCreate: "/monitor",
  monitorUpdate: (id: string): string => `/monitor/${encodeURIComponent(id)}`,
  monitorStatusList: "/monitor-status/get-list",
  incidentSeverityList: "/incident-severity/get-list",
  onCallPolicyList: "/on-call-duty-policy/get-list",
} as const;
export const PAGE_SIZE = 100;
/** Stop paging after this many rows (a broken `count` must not loop forever). */
export const MAX_ROWS = 10000;

export function oneUptimeClient(opts: { url: string; projectId: string; secrets: Secrets; fetch: FetchFn; allowWrites: boolean }): ApiClient {
  return new ApiClient({
    baseUrl: `${opts.url.replace(/\/+$/, "")}${API_PREFIX}`,
    headers: {
      // Cloudflare Access service token: OneUptime sits behind the staff login.
      "CF-Access-Client-Id": opts.secrets.require("ONEUP_ACCESS_CLIENT_ID"),
      "CF-Access-Client-Secret": opts.secrets.require("ONEUP_ACCESS_CLIENT_SECRET"),
      ApiKey: opts.secrets.require("ONEUPTIME_API_KEY"),
      ProjectID: opts.projectId,
    },
    fetch: opts.fetch,
    allowWrites: opts.allowWrites,
    name: "oneuptime",
  });
}

interface ListPage {
  count?: number;
  data?: unknown[];
}

/** Every row of a list endpoint (POST get-list is a read), page by page. */
export async function listAll(client: ApiClient, path: string, select: Record<string, boolean>): Promise<Record<string, unknown>[]> {
  const out: Record<string, unknown>[] = [];
  for (let skip = 0; skip < MAX_ROWS; skip += PAGE_SIZE) {
    const page = await client.request<ListPage>("POST", path, {
      query: { skip, limit: PAGE_SIZE },
      body: { query: {}, select, sort: { createdAt: "ASC" } },
      read: true,
    });
    const rows = Array.isArray(page.data) ? page.data : [];
    for (const r of rows) if (r && typeof r === "object") out.push(r as Record<string, unknown>);
    const count = typeof page.count === "number" ? page.count : undefined;
    if (rows.length < PAGE_SIZE || (count !== undefined && out.length >= count)) break;
  }
  return out;
}

// ---------- reading rows ----------

/** Unwraps OneUptime's { _type, value } serialisation (ObjectID, URL, MonitorSteps...). */
export function unwrap(v: unknown): unknown {
  if (v && typeof v === "object" && !Array.isArray(v) && "_type" in v && "value" in v) return (v as { value: unknown }).value;
  return v;
}

const str = (v: unknown): string | undefined => {
  const u = unwrap(v);
  return typeof u === "string" ? u : typeof u === "number" ? String(u) : undefined;
};
const obj = (v: unknown): Record<string, unknown> => {
  const u = unwrap(v);
  return u && typeof u === "object" && !Array.isArray(u) ? (u as Record<string, unknown>) : {};
};
const arr = (v: unknown): unknown[] => {
  const u = unwrap(v);
  return Array.isArray(u) ? u : [];
};
/** A number, also when sent as a string (the dashboard saves some numbers as strings). */
const num = (v: unknown): number | null => {
  const u = unwrap(v);
  const n = typeof u === "number" ? u : typeof u === "string" && u.trim() !== "" ? Number(u) : NaN;
  return Number.isFinite(n) ? n : null;
};

export const rowId = (r: Record<string, unknown>): string | undefined => str(r["_id"]) ?? str(r["id"]);

