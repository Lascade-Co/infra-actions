export interface MonitorStatusRef {
  id: string;
  name: string;
  operational: boolean;
  offline: boolean;
  priority: number;
}
export interface SeverityRef {
  id: string;
  name: string;
  order: number;
}

export const STATUS_SELECT = { _id: true, name: true, isOperationalState: true, isOfflineState: true, priority: true } as const;
export const SEVERITY_SELECT = { _id: true, name: true, order: true } as const;
export const POLICY_SELECT = { _id: true, name: true } as const;

export function readStatus(r: Record<string, unknown>): MonitorStatusRef | undefined {
  const id = rowId(r);
  if (!id) return undefined;
  return {
    id,
    name: str(r["name"]) ?? id,
    operational: r["isOperationalState"] === true,
    offline: r["isOfflineState"] === true,
    priority: typeof r["priority"] === "number" ? r["priority"] : Number.MAX_SAFE_INTEGER,
  };
}

export function readSeverity(r: Record<string, unknown>): SeverityRef | undefined {
  const id = rowId(r);
  if (!id) return undefined;
  return { id, name: str(r["name"]) ?? id, order: typeof r["order"] === "number" ? r["order"] : Number.MAX_SAFE_INTEGER };
}

// ---------- what the tool writes ----------

export const MONITOR_TYPE = "Website";
/** Every minute (CronTime.EVERY_MINUTE; the fastest a probe can do). */
export const MONITORING_INTERVAL = "* * * * *";
/**
 * Paging noise (as the Worker's FAILS_TO_ALERT): a site is marked offline, and the incident opens,
 * only when every check of the last DOWN_AFTER_MINUTES minutes failed. Recovery is immediate.
 */
export const DOWN_AFTER_MINUTES = 3;
/** As the Worker's probe: give up on one attempt after this long (its PROBE_TIMEOUT_MS was 8 s). */
export const REQUEST_TIMEOUT_MS = 10000;
/**
 * As the Worker's re-probe of a failed check (RETRY_DELAY_MS): retries after the first attempt
 * within one check, so one dropped request or timeout doesn't count as a failed minute.
 * 3 attempts x REQUEST_TIMEOUT_MS stays inside the one-minute interval.
 */
export const RETRY_COUNT = 2;
/** Criteria names: they identify the tool's criteria on an update (their ids are carried over). */
export const CRITERION = {
  app404: "infra-sync: app 404 counts as up",
  offline: "infra-sync: offline",
  online: "infra-sync: online",
} as const;
export type CriterionRole = keyof typeof CRITERION;
/** Text of a Cloudflare 1xxx error body ("error code: 1033"); an app 404 carrying it is not accepted. */
export const CLOUDFLARE_ERROR_TEXT = "error code: 1";

/** One monitor as the tool wants it, in OneUptime-neutral terms. */
export interface MonitorWant {
  name: string;
  description: string;
  url: string;
  acceptApp404: boolean;
  onCallPolicyIds: string[];
}

/** The project's ids every monitor refers to. */
export interface ProjectIds {
  operationalStatusId: string;
  offlineStatusId: string;
  incidentSeverityId: string;
}

/** Ids of an existing monitor's parts, carried into an update so OneUptime keeps its history. */
export interface PartIds {
  step?: string;
  criteria?: Partial<Record<CriterionRole, string>>;
  incident?: string;
}

const filter = (checkOn: string, filterType: string, value?: number | string): Json =>
  value === undefined ? { checkOn, filterType } : { checkOn, filterType, value };

/** A filter that matches only when every check of the last DOWN_AFTER_MINUTES minutes matched. */
const sustained = (checkOn: string, filterType: string, value?: number | string): Json => ({
  ...(filter(checkOn, filterType, value) as Record<string, Json>),
  evaluateOverTime: true,
  evaluateOverTimeOptions: { timeValueInMinutes: DOWN_AFTER_MINUTES, evaluateOverTimeType: "All Values" },
});

/** The `data` of a create (with monitorType) or update (without: it can't change). */
export function monitorData(want: MonitorWant, project: ProjectIds, ids: PartIds, newId: () => string, forCreate: boolean): Record<string, Json> {
  const cid = (role: CriterionRole): string => ids.criteria?.[role] ?? newId();
  const criterion = (role: CriterionRole, filterCondition: "All" | "Any", filters: Json[], statusId: string, incident?: Json): Json => ({
    _type: "MonitorCriteriaInstance",
    value: {
      id: cid(role),
      name: CRITERION[role],
      description: "",
      filterCondition,
      filters,
      changeMonitorStatus: true,
      monitorStatusId: statusId,
      createIncidents: incident !== undefined,
      incidents: incident !== undefined ? [incident] : [],
      createAlerts: false,
      alerts: [],
    },
  });
  const criteria: Json[] = [];
  if (want.acceptApp404) {
    // First: "offline", which comes later, would match its 404 (criteria are judged in order).
    criteria.push(
      criterion(
        "app404",
        "All",
        [
          filter("Is Online", "True"),
          filter("Response Status Code", "Equal To", 404),
          // Matches nothing on an empty body, so the tunnel's empty 404 stays a failure.
          filter("Response Body", "Not Contains", CLOUDFLARE_ERROR_TEXT),
        ],
        project.operationalStatusId,
      ),
    );
  }
  // Healthy before offline: criteria are judged in order and the first match decides, and offline
  // is judged from its stored windows. So a check that is healthy now is never marked down,
  // whether or not the server has stored it in the window yet; recovery is immediate.
  criteria.push(
    criterion(
      "online",
      "All",
      [filter("Is Online", "True"), filter("Response Status Code", "Greater Than Or Equal To", 200), filter("Response Status Code", "Less Than", 400)],
      project.operationalStatusId,
    ),
    criterion(
      "offline",
      "Any",
      // Each filter is judged over its own window: down after DOWN_AFTER_MINUTES minutes of no
      // answer, or of error answers. Timeouts count as "not online" (OneUptime has no
      // "inconclusive"), but the status-code window skips them, as the Worker did.
      [
        sustained("Is Online", "False"),
        sustained("Response Status Code", "Greater Than Or Equal To", 400),
        sustained("Response Status Code", "Less Than", 200),
      ],
      project.offlineStatusId,
      {
        id: ids.incident ?? newId(),
        title: `${want.name} is down`,
        description: `${want.url} did not answer with 2xx/3xx${want.acceptApp404 ? " or the app's own 404" : ""} for ${DOWN_AFTER_MINUTES} minutes.`,
        incidentSeverityId: project.incidentSeverityId,
        autoResolveIncident: true,
        onCallPolicyIds: [...want.onCallPolicyIds],
      },
    ),
  );
  const monitorSteps: Json = {
    _type: "MonitorSteps",
    value: {
      monitorStepsInstanceArray: [
        {
          _type: "MonitorStep",
          value: {
            id: ids.step ?? newId(),
            monitorDestination: { _type: "URL", value: want.url },
            requestType: "GET",
            // As the Worker's probe (redirect: "manual"): a 3xx, such as the staff login's 302, is up.
            doNotFollowRedirects: true,
            requestTimeoutInMs: REQUEST_TIMEOUT_MS,
            retryCount: RETRY_COUNT,
            monitorCriteria: { _type: "MonitorCriteria", value: { monitorCriteriaInstanceArray: criteria } },
          },
        },
      ],
      defaultMonitorStatusId: project.operationalStatusId,
    },
  };
  return {
    name: want.name,
    description: want.description,
    ...(forCreate ? { monitorType: MONITOR_TYPE } : {}),
    monitoringInterval: MONITORING_INTERVAL,
    monitorSteps,
  };
}

// ---------- the comparable view (plan before/after) ----------

/**
 * The fields the tool sets, normalised so the same monitor reads the same whether it was built
 * here or read back from the API (ids, `_type` wrappers and number-vs-string values dropped).
 * Status and severity ids show as names.
 */
export type MonitorView = {
  name: string;
  description: string;
  type: string;
  interval: string;
  url: string;
  method: string;
  followRedirects: boolean;
  /** null when the API returns none (OneUptime's defaults then apply: 60 s, 3 retries). */
  requestTimeoutMs: number | null;
  retryCount: number | null;
  acceptApp404: boolean;
  onCallPolicyIds: string[];
  defaultStatus: string;
  steps: number;
  criteria: string[];
};

export interface Names {
  statuses: ReadonlyMap<string, string>;
  severities: ReadonlyMap<string, string>;
}

const named = (m: ReadonlyMap<string, string>, id: string | undefined): string => (id ? (m.get(id) ?? id) : "none");

function criterionText(c: Record<string, unknown>, names: Names): string {
  const filters = arr(c["filters"]).map((f) => {
    const o = obj(f);
    const v = str(o["value"]);
    const base = `${str(o["checkOn"]) ?? "?"} ${str(o["filterType"]) ?? "?"}${v !== undefined && v !== "" ? ` ${v}` : ""}`;
    if (o["evaluateOverTime"] !== true) return base;
    const opts = obj(o["evaluateOverTimeOptions"]);
    return `${base} (${str(opts["evaluateOverTimeType"]) ?? "?"} over ${str(opts["timeValueInMinutes"]) ?? "?"} min)`;
  });
  const parts = [`${str(c["name"]) ?? ""} [${str(c["filterCondition"]) ?? "?"}]: ${filters.join("; ")}`];
  parts.push(c["changeMonitorStatus"] === true ? `status ${named(names.statuses, str(c["monitorStatusId"]))}` : "no status change");
  if (c["createIncidents"] === true) {
    for (const i of arr(c["incidents"])) {
      const o = obj(i);
      const policies = arr(o["onCallPolicyIds"])
        .map(str)
        .filter((x): x is string => !!x)
        .sort();
      parts.push(
        `incident "${str(o["title"]) ?? ""}" (${named(names.severities, str(o["incidentSeverityId"]))}${o["autoResolveIncident"] === true ? ", auto-resolve" : ""}, on-call ${policies.join(",") || "none"})`,
      );
    }
  }
  if (c["createAlerts"] === true) parts.push(`${arr(c["alerts"]).length} alert(s)`);
  return parts.join(" -> ");
}

/** Reads a monitor's `data` (as built above) or an API row into the comparable view. */
export function monitorView(row: Record<string, unknown>, names: Names): MonitorView {
  const steps = arr(obj(row["monitorSteps"])["monitorStepsInstanceArray"]).map(obj);
  const step = steps[0] ?? {};
  const criteria = arr(obj(step["monitorCriteria"])["monitorCriteriaInstanceArray"]).map(obj);
  const policies = new Set<string>();
  for (const c of criteria) {
    if (c["createIncidents"] !== true) continue;
    for (const i of arr(c["incidents"])) for (const p of arr(obj(i)["onCallPolicyIds"])) if (str(p)) policies.add(str(p)!);
  }
  return {
    name: str(row["name"]) ?? "",
    description: str(row["description"]) ?? "",
    type: str(row["monitorType"]) ?? "",
    interval: str(row["monitoringInterval"]) ?? "",
    url: str(step["monitorDestination"]) ?? "",
    method: str(step["requestType"]) ?? "GET",
    followRedirects: step["doNotFollowRedirects"] !== true,
    requestTimeoutMs: num(step["requestTimeoutInMs"]),
    retryCount: num(step["retryCount"]),
    acceptApp404: criteria.some((c) => str(c["name"]) === CRITERION.app404),
    onCallPolicyIds: [...policies].sort(),
    defaultStatus: named(names.statuses, str(obj(row["monitorSteps"])["defaultMonitorStatusId"])),
    steps: steps.length,
    criteria: criteria.map((c) => criterionText(c, names)),
  };
}

/** Ids of the parts of an existing monitor the tool recognises (for an update). */
export function partIds(row: Record<string, unknown>): PartIds {
  const step = obj(arr(obj(row["monitorSteps"])["monitorStepsInstanceArray"])[0]);
  const ids: PartIds = { criteria: {} };
  const stepId = str(step["id"]);
  if (stepId) ids.step = stepId;
  for (const c of arr(obj(step["monitorCriteria"])["monitorCriteriaInstanceArray"]).map(obj)) {
    const role = (Object.keys(CRITERION) as CriterionRole[]).find((r) => CRITERION[r] === str(c["name"]));
    const id = str(c["id"]);
    if (!role || !id || ids.criteria![role]) continue;
    ids.criteria![role] = id;
    if (role === "offline") {
      const inc = str(obj(arr(c["incidents"])[0])["id"]);
      if (inc) ids.incident = inc;
    }
  }
  return ids;
}
